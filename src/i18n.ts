/**
 * Lingua della Regia: quella scelta a mano (?lang=it|en nell'indirizzo, poi ricordata su questo PC),
 * altrimenti quella di sistema: italiano se il sistema è in italiano, altrimenti inglese.
 */
const chosen = (): "it" | "en" | null => {
  try {
    const q = new URLSearchParams(location.search).get("lang");
    if (q === "it" || q === "en") localStorage.setItem("obsyard.lang", q);
    const v = localStorage.getItem("obsyard.lang");
    return v === "it" || v === "en" ? v : null;
  } catch {
    return null;
  }
};
export const lang = ref<"it" | "en">(chosen() ?? ((navigator.language || "it").toLowerCase().startsWith("it") ? "it" : "en"));

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = (lang.value === "en" ? en[key] : undefined) ?? it[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
